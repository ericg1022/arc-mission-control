#!/usr/bin/env node
'use strict';
// Searches for a better fresh-campaign route and stores it in route-seed.js,
// which every new campaign starts from. The browser keeps improving routes
// from there; this just gives everyone a strong starting point.
//
//   node tools/optimize-seed.js [seconds per run=60] [runs=4]
const fs=require('fs'),path=require('path'),vm=require('vm');
const ROOT=path.join(__dirname,'..');
const ctx={};ctx.globalThis=ctx;
for(const f of ['offline-resources.js','route-seed.js','route-planner.js'])vm.runInNewContext(fs.readFileSync(path.join(ROOT,f),'utf8'),ctx);
const seconds=+process.argv[2]||60,runs=+process.argv[3]||4;
const p=ctx.ARCPlanner.create(ctx.ARCOffline.data),fresh={completed:[],objectives:{},raids:[]};
let best=p.replay(fresh,null,ctx.ARCSeed);
console.log('current seed:',best?best.score.join('/'):'invalid for this data');
for(let run=1;run<=runs;run++){
 const r=p.search(fresh,null,{prior:best?.steps,timeLimit:seconds*1000,seed:run});
 console.log(`run ${run}: ${r.score.join('/')} (raids/map changes/one-quest raids)`);
 best=p.better(best,r);
}
const check=p.replay(fresh,null,best.steps);
if(!check||check.remaining)throw Error('Best route does not replay to a finished campaign');
const seed=check.steps.map(r=>({map:r.map,number:r.number,quests:r.quests}));
if(JSON.stringify(seed)===JSON.stringify(ctx.ARCSeed)){console.log('route-seed.js is already the best route found.');process.exit(0)}
fs.writeFileSync(path.join(ROOT,'route-seed.js'),`// Generated by tools/optimize-seed.js: ${check.score[0]} raids, ${check.score[1]} map changes, ${check.score[2]} one-quest raids.\nglobalThis.ARCSeed=${JSON.stringify(seed)};\n`);
console.log('Wrote route-seed.js:',check.score.join('/'));
